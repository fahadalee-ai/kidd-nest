const GALLERY = ["entrance", "reception", "nap", "playground", "art", "garden", "lunch", "library", "music", "stem"];

function make(input: Input): Provider {
  const monthly = input.monthly ?? 0;
  return {
    ...input,
    city: "Austin",
    state: "TX",
    openNow: input.openNow ?? true,
    nutFree: input.nutFree ?? false,
    days: input.days ?? ["Mon", "Tue", "Wed", "Thu", "Fri"],
    monthly,
    background: { status: "Clear", date: "March 12, 2026", vendor: "Checkr" },
    license: input.license ?? null,
    rates: input.rates ?? [
      { label: "Hourly", amount: `$${input.hourly}/hr` },
      { label: "Daily", amount: `$${Math.round(input.hourly * 8)}` },
      { label: "Weekly", amount: `$${input.weeklyCost}` },
      { label: "Monthly", amount: monthly ? `$${monthly.toLocaleString()}` : "—" },
      { label: "Registration", amount: monthly ? "$150" : "$0" },
      { label: "Late pickup", amount: "$1/min after 10 min" },
    ],
    safety: SAFETY,
    policies: POLICIES,
  };
}

